-- NSS Volunteering Drives Management System
-- MySQL / XAMPP
-- Run this file first.

CREATE DATABASE IF NOT EXISTS nss_drives;
USE nss_drives;

SET FOREIGN_KEY_CHECKS = 0;
DROP TABLE IF EXISTS CERTIFICATE;
DROP TABLE IF EXISTS CERTIFIES;
DROP TABLE IF EXISTS EARNS;
DROP TABLE IF EXISTS AWARD;
DROP TABLE IF EXISTS ATTENDS;
DROP TABLE IF EXISTS COLLABORATES_WITH;
DROP TABLE IF EXISTS PARTNER_ORG;
DROP TABLE IF EXISTS FUNDED_BY;
DROP TABLE IF EXISTS SPONSOR;
DROP TABLE IF EXISTS SESSION;
DROP TABLE IF EXISTS VENUE;
DROP TABLE IF EXISTS DRIVE;
DROP TABLE IF EXISTS COORDINATOR;
DROP TABLE IF EXISTS STUDENT_VOLUNTEER;
DROP TABLE IF EXISTS VOLUNTEER_PHONE;
DROP TABLE IF EXISTS VOLUNTEER;
SET FOREIGN_KEY_CHECKS = 1;

CREATE TABLE VOLUNTEER (
    Volunteer_ID INT PRIMARY KEY,
    First_Name VARCHAR(50) NOT NULL,
    Last_Name VARCHAR(50) NOT NULL,
    Email VARCHAR(120) NOT NULL UNIQUE,
    Gender VARCHAR(20) NOT NULL
) ENGINE=InnoDB;

CREATE TABLE VOLUNTEER_PHONE (
    Volunteer_ID INT NOT NULL,
    Phone_No VARCHAR(15) NOT NULL,
    PRIMARY KEY (Volunteer_ID, Phone_No),
    CONSTRAINT fk_phone_volunteer
        FOREIGN KEY (Volunteer_ID) REFERENCES VOLUNTEER(Volunteer_ID)
        ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB;

CREATE TABLE STUDENT_VOLUNTEER (
    Volunteer_ID INT PRIMARY KEY,
    Roll_No VARCHAR(20) NOT NULL UNIQUE,
    Branch VARCHAR(50) NOT NULL,
    `Year` TINYINT NOT NULL,
    CONSTRAINT fk_student_volunteer
        FOREIGN KEY (Volunteer_ID) REFERENCES VOLUNTEER(Volunteer_ID)
        ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB;

CREATE TABLE COORDINATOR (
    Volunteer_ID INT PRIMARY KEY,
    Department VARCHAR(80) NOT NULL,
    Office_No VARCHAR(20) NOT NULL,
    CONSTRAINT fk_coordinator_volunteer
        FOREIGN KEY (Volunteer_ID) REFERENCES VOLUNTEER(Volunteer_ID)
        ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB;

CREATE TABLE DRIVE (
    Drive_ID INT PRIMARY KEY,
    Drive_Name VARCHAR(120) NOT NULL,
    Cause VARCHAR(100) NOT NULL,
    Start_Date DATE NOT NULL,
    End_Date DATE NOT NULL,
    CONSTRAINT chk_drive_dates CHECK (End_Date >= Start_Date)
) ENGINE=InnoDB;

CREATE TABLE VENUE (
    Venue_ID INT PRIMARY KEY,
    Venue_Name VARCHAR(120) NOT NULL,
    Address VARCHAR(255) NOT NULL,
    Capacity INT NOT NULL CHECK (Capacity > 0)
) ENGINE=InnoDB;

CREATE TABLE SESSION (
    Drive_ID INT NOT NULL,
    Session_No INT NOT NULL,
    Venue_ID INT NOT NULL,
    Start_Time DATETIME NOT NULL,
    End_Time DATETIME NOT NULL,
    PRIMARY KEY (Drive_ID, Session_No),
    CONSTRAINT fk_session_drive
        FOREIGN KEY (Drive_ID) REFERENCES DRIVE(Drive_ID)
        ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_session_venue
        FOREIGN KEY (Venue_ID) REFERENCES VENUE(Venue_ID)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT chk_session_time CHECK (End_Time > Start_Time)
) ENGINE=InnoDB;

CREATE TABLE SPONSOR (
    Sponsor_ID INT PRIMARY KEY,
    Sponsor_Name VARCHAR(120) NOT NULL,
    Sponsor_Type VARCHAR(60) NOT NULL,
    Contact VARCHAR(30) NOT NULL
) ENGINE=InnoDB;

CREATE TABLE FUNDED_BY (
    Sponsor_ID INT NOT NULL,
    Drive_ID INT NOT NULL,
    Amount DECIMAL(12,2) NOT NULL CHECK (Amount >= 0),
    PRIMARY KEY (Sponsor_ID, Drive_ID),
    CONSTRAINT fk_funded_sponsor
        FOREIGN KEY (Sponsor_ID) REFERENCES SPONSOR(Sponsor_ID)
        ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_funded_drive
        FOREIGN KEY (Drive_ID) REFERENCES DRIVE(Drive_ID)
        ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB;

CREATE TABLE PARTNER_ORG (
    Org_ID INT PRIMARY KEY,
    Org_Name VARCHAR(120) NOT NULL,
    Org_Type VARCHAR(60) NOT NULL,
    Address VARCHAR(255) NOT NULL
) ENGINE=InnoDB;

CREATE TABLE COLLABORATES_WITH (
    Org_ID INT NOT NULL,
    Drive_ID INT NOT NULL,
    Partner_Role VARCHAR(120) NOT NULL,
    PRIMARY KEY (Org_ID, Drive_ID),
    CONSTRAINT fk_collab_org
        FOREIGN KEY (Org_ID) REFERENCES PARTNER_ORG(Org_ID)
        ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_collab_drive
        FOREIGN KEY (Drive_ID) REFERENCES DRIVE(Drive_ID)
        ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB;

CREATE TABLE ATTENDS (
    Volunteer_ID INT NOT NULL,
    Drive_ID INT NOT NULL,
    Session_No INT NOT NULL,
    Check_In_Time DATETIME NOT NULL,
    PRIMARY KEY (Volunteer_ID, Drive_ID, Session_No),
    CONSTRAINT fk_attends_student
        FOREIGN KEY (Volunteer_ID) REFERENCES STUDENT_VOLUNTEER(Volunteer_ID)
        ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_attends_session
        FOREIGN KEY (Drive_ID, Session_No) REFERENCES SESSION(Drive_ID, Session_No)
        ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB;

CREATE TABLE AWARD (
    Award_ID INT PRIMARY KEY,
    Award_Name VARCHAR(120) NOT NULL,
    Category VARCHAR(80) NOT NULL
) ENGINE=InnoDB;

CREATE TABLE EARNS (
    Volunteer_ID INT NOT NULL,
    Drive_ID INT NOT NULL,
    Session_No INT NOT NULL,
    Award_ID INT NOT NULL,
    PRIMARY KEY (Volunteer_ID, Drive_ID, Session_No),
    CONSTRAINT fk_earns_attendance
        FOREIGN KEY (Volunteer_ID, Drive_ID, Session_No)
        REFERENCES ATTENDS(Volunteer_ID, Drive_ID, Session_No)
        ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_earns_award
        FOREIGN KEY (Award_ID) REFERENCES AWARD(Award_ID)
        ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB;

CREATE TABLE CERTIFIES (
    Volunteer_ID INT NOT NULL,
    Drive_ID INT NOT NULL,
    Session_No INT NOT NULL,
    Coordinator_ID INT NOT NULL,
    Hours DECIMAL(5,2) NOT NULL,
    Certified_On DATE NOT NULL,
    PRIMARY KEY (Volunteer_ID, Drive_ID, Session_No),
    CONSTRAINT fk_certifies_attendance
        FOREIGN KEY (Volunteer_ID, Drive_ID, Session_No)
        REFERENCES ATTENDS(Volunteer_ID, Drive_ID, Session_No)
        ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_certifies_coordinator
        FOREIGN KEY (Coordinator_ID) REFERENCES COORDINATOR(Volunteer_ID)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT chk_certified_hours CHECK (Hours > 0)
) ENGINE=InnoDB;

CREATE TABLE CERTIFICATE (
    Volunteer_ID INT NOT NULL,
    Certificate_No VARCHAR(30) NOT NULL,
    PRIMARY KEY (Volunteer_ID, Certificate_No),
    CONSTRAINT fk_certificate_student
        FOREIGN KEY (Volunteer_ID) REFERENCES STUDENT_VOLUNTEER(Volunteer_ID)
        ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB;
